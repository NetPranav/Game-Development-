import os
root_dir = r"A:\UNREAL PROJECT\Game\GameAnimationSample"
rows = []
for root, _, files in os.walk(os.path.join(root_dir, "Source")):
    for f in sorted(files):
        if f.endswith((".h", ".cpp", ".cs")):
            full = os.path.join(root, f)
            rel = os.path.relpath(full, root_dir).replace(os.sep, "/")
            n = sum(1 for _ in open(full, encoding="utf-8", errors="ignore"))
            rows.append(f"- {rel}  ({n} lines)")
rows.sort()
with open(os.path.join(root_dir, "Docs", "reports", "FILE_INDEX.md"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write("# Source file index (generated by reviewer; files created after generation are not listed)\n\n" + "\n".join(rows) + "\n")
print(len(rows), "files")
